import i18n from "i18next";

/**
 * 後端動態拼接的報錯消息（消息裡嵌了變量，如「審批規則「xxx」尚未配置審批層級」）。
 * 這類消息命中不了 en.json 的靜態鍵，故英文下會保持繁體原文——本模組補上這個缺口。
 *
 * 每條 pattern：`re` 匹配後端繁體原文並捕獲變量，`tpl` 是繁體框架模板（同時也是 en.json 的
 * key），用 `{{v}}` 佔位。命中後把捕獲的變量回填進模板再查表。
 *
 * 變量本身會再過一次 `i18n.t()`：
 *   - 若是枚舉名（如「請假」「審批中」，已收錄靜態鍵）→ 被譯成英文；
 *   - 若是 DB 名（職位/規則/員工名）→ 原樣返回。
 *
 * zh-Hans 由 opencc 後處理器把整串轉簡體，無需本模組介入；故 request.ts 僅在 en 未命中
 * 靜態鍵時才調用這裡。
 */
interface DynPattern {
  re: RegExp;
  tpl: string;
}

const PATTERNS: DynPattern[] = [
  { re: /^條件配置格式錯誤：(.+)$/s, tpl: "條件配置格式錯誤：{{v}}" },
  {
    re: /^尚未配置「(.+)」的審批規則，請聯繫 HR$/s,
    tpl: "尚未配置「{{v}}」的審批規則，請聯繫 HR",
  },
  {
    re: /^審批規則「(.+)」尚未配置審批層級$/s,
    tpl: "審批規則「{{v}}」尚未配置審批層級",
  },
  {
    re: /^找不到「(.+)」的審批人，請聯繫 HR 檢查審批規則配置$/s,
    tpl: "找不到「{{v}}」的審批人，請聯繫 HR 檢查審批規則配置",
  },
  {
    re: /^(.+) 已是本節點的審批人，無需轉簽$/s,
    tpl: "{{v}} 已是本節點的審批人，無需轉簽",
  },
  { re: /^此單據已「(.+)」，無法再操作$/s, tpl: "此單據已「{{v}}」，無法再操作" },
  {
    re: /^層級「(.+)」為指定職位，必須選擇職位$/s,
    tpl: "層級「{{v}}」為指定職位，必須選擇職位",
  },
  {
    re: /^層級「(.+)」指定的職位不存在$/s,
    tpl: "層級「{{v}}」指定的職位不存在",
  },
  {
    re: /^層級「(.+)」為指定人員，必須選擇員工$/s,
    tpl: "層級「{{v}}」為指定人員，必須選擇員工",
  },
  {
    re: /^層級「(.+)」指定的員工不存在$/s,
    tpl: "層級「{{v}}」指定的員工不存在",
  },
  // 績效模組
  {
    re: /^指標「(.+)」評分需在 0~(.+) 之間$/s,
    tpl: "指標「{{v}}」評分需在 0~{{v2}} 之間",
  },
  { re: /^導出失敗：(.+)$/s, tpl: "導出失敗：{{v}}" },
  {
    re: /^自評\/互評\/主管評權重合計必須為100%，當前為(.+)%$/s,
    tpl: "自評/互評/主管評權重合計必須為100%，當前為{{v}}%",
  },
  { re: /^指標分類不合法：(.+)$/s, tpl: "指標分類不合法：{{v}}" },
  { re: /^評分方式不合法：(.+)$/s, tpl: "評分方式不合法：{{v}}" },
  { re: /^指標權重不合法：(.+)$/s, tpl: "指標權重不合法：{{v}}" },
  {
    re: /^指標權重合計必須為100%，當前為(.+)%$/s,
    tpl: "指標權重合計必須為100%，當前為{{v}}%",
  },
  { re: /^評級區間不合法：(.+)$/s, tpl: "評級區間不合法：{{v}}" },
];

/**
 * 嘗試翻譯後端動態拼接的報錯。命中框架則回填變量並查表返回；未命中返回 null（調用方回退原文）。
 */
export function translateDynamic(msg: string): string | null {
  for (const { re, tpl } of PATTERNS) {
    const m = re.exec(msg);
    if (m) {
      // 逐個捕獲組回填：第 1 組 → {{v}}，其餘 → {{v2}}、{{v3}}…
      // 每個變量再過一次 t()（枚舉名被譯、DB 名/數字原樣返回）。
      const params: Record<string, string> = {};
      for (let i = 1; i < m.length; i++) {
        params[i === 1 ? "v" : `v${i}`] = i18n.t(m[i].trim());
      }
      return i18n.t(tpl, params);
    }
  }
  return null;
}
